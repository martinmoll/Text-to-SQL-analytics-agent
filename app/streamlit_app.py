# ── Helper rendering functions ───────────────────────────────────────────────


def _render_trace(trace: list[dict]) -> None:
    """Render the agent's reasoning trace as a step-by-step timeline."""

    step_labels = {
        "clarify": ("1. Clarify", "Interpreted the question"),
        "resolve": ("2. Resolve", "Checked the semantic layer"),
        "query": ("3. Query", "Generated SQL"),
        "review": ("4. Review", "Adversarial review"),
        "execute": ("5. Execute", "Ran query against DuckDB"),
    }

    for step_data in trace:
        step_name = step_data.get("step", "unknown")
        label, description = step_labels.get(step_name, (step_name.title(), ""))

        with st.expander(f"**{label}** — {description}", expanded=False):
            if step_name == "clarify":
                interpreted = step_data.get("interpreted", "")
                metric_type = step_data.get("metric_type", "")
                error = step_data.get("error")
                if error:
                    st.warning(f"LLM clarification unavailable: {error}")
                if interpreted:
                    st.markdown(f"**Interpreted as:** {interpreted}")
                if metric_type:
                    st.markdown(f"**Metric type:** `{metric_type}`")

            elif step_name == "resolve":
                found = step_data.get("found", False)
                metric = step_data.get("metric")
                candidates = step_data.get("candidates", [])
                if found:
                    st.success(f"Semantic layer hit: `{metric}`")
                else:
                    st.warning("No governed metric found — falling through to LLM generation")
                if candidates:
                    st.markdown(f"**Candidates considered:** {', '.join(f'`{c}`' for c in candidates)}")

            elif step_name == "query":
                source = step_data.get("source", "")
                if source == "semantic_layer":
                    st.success(f"SQL compiled from semantic layer metric: `{step_data.get('metric', '')}`")
                elif source == "llm_generated":
                    ref = step_data.get("reference", "none")
                    st.info(f"SQL generated by LLM (reference doc: `{ref}`)")
                    preview = step_data.get("reasoning_preview", "")
                    if preview:
                        st.text(preview)

            elif step_name == "review":
                passed = step_data.get("passed", True)
                issues = step_data.get("issues", 0)
                summary = step_data.get("summary", "")
                if passed:
                    st.success(f"Review passed. {summary}")
                else:
                    st.error(f"Review found {issues} issue(s). {summary}")

            elif step_name == "execute":
                success = step_data.get("success", False)
                rows = step_data.get("rows", 0)
                if success:
                    st.success(f"Query returned {rows} row(s)")
                else:
                    st.error("Query execution failed")


def _render_provenance(provenance) -> None:
    """Render the provenance footer as a compact row of metrics."""
    cols = st.columns(5)

    with cols[0]:
        st.metric("Source", ", ".join(provenance.source_tables) if provenance.source_tables else "—")
    with cols[1]:
        st.metric("Freshness", provenance.data_freshness or "—")
    with cols[2]:
        st.metric("Currency", provenance.currency or "—")
    with cols[3]:
        st.metric("Coverage", provenance.coverage or "—")
    with cols[4]:
        st.metric("Metric Source", provenance.metric_source or "—")

    if provenance.review_summary:
        st.caption(f"Review: {provenance.review_summary}")


