# ── Agent setup ──────────────────────────────────────────────────────────────

@st.cache_resource
def get_agent(db_path: str, review_enabled: bool) -> AnalyticsAgent:
    return AnalyticsAgent(db_path=db_path, review_enabled=review_enabled)


# ── Example questions ────────────────────────────────────────────────────────

EXAMPLES = [
    "What was AAPL's Sharpe ratio in 2024?",
    "Compare the cumulative returns of MSFT and GOOGL in Q1 2024",
    "What is the beta of TSLA relative to the S&P 500 in 2024?",
    "Which stock had the highest annualized volatility in 2024?",
    "What is the correlation between EQNR.OL and DNB.OL in 2024?",
    "How did the S&P 500 perform in 2024?",
    "What was NVDA's maximum drawdown in 2024?",
]


# ── Main UI ──────────────────────────────────────────────────────────────────

st.header("Ask a question")

# Example question chips
selected_example = None
cols = st.columns(4)
for i, example in enumerate(EXAMPLES[:4]):
    with cols[i]:
        if st.button(example[:45] + "..." if len(example) > 45 else example, key=f"ex_{i}", use_container_width=True):
            selected_example = example

if len(EXAMPLES) > 4:
    cols2 = st.columns(4)
    for i, example in enumerate(EXAMPLES[4:]):
        with cols2[i]:
            if st.button(example[:45] + "..." if len(example) > 45 else example, key=f"ex2_{i}", use_container_width=True):
                selected_example = example

question = st.text_input(
    "Your question",
    value=selected_example or "",
    placeholder="e.g., What was the Sharpe ratio of AAPL vs MSFT in 2024?",
    label_visibility="collapsed",
)

if question:
    agent = get_agent(db_path, review_enabled)

    with st.spinner("Processing..."):
        try:
            response: AgentResponse = agent.answer(question)
        except Exception as e:
            st.error(f"Agent error: {e}")
            st.stop()

    # ── Answer ───────────────────────────────────────────────────────────
    st.subheader("Answer")
    st.markdown(response.answer)

    if response.methodology:
        st.caption(response.methodology)

    # ── Warnings ─────────────────────────────────────────────────────────
    if response.warnings:
        with st.expander(f"Warnings ({len(response.warnings)})", expanded=False):
            for w in response.warnings:
                st.warning(w, icon="⚠️")

    # ── Results, SQL, Trace tabs ─────────────────────────────────────────
    tab_results, tab_sql, tab_trace = st.tabs(["Results", "SQL", "Reasoning Trace"])

    with tab_results:
        if response.data is not None and not response.data.empty:
            st.dataframe(response.data, use_container_width=True, hide_index=True)
        else:
            st.info("No data returned.")

    with tab_sql:
        if response.sql:
            st.code(response.sql, language="sql")
        else:
            st.info("No SQL generated.")

    with tab_trace:
        if response.trace:
            _render_trace(response.trace)
        else:
            st.info("No trace available.")

    # ── Provenance footer ────────────────────────────────────────────────
    if response.provenance:
        st.divider()
        _render_provenance(response.provenance)
